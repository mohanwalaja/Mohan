/**
 * Regenerates src/lib/astrology/nutationSeries.ts from the SAME IAU 1980
 * 63-term nutation table the PHP engine loads
 * (api/astrology/ephemeris_tables.php).
 *
 * The Node and PHP engines must apply an identical Δψ when they convert the
 * mean Lahiri ayanamsa into the true one, so the series is generated from the
 * PHP source of truth rather than being typed out by hand in both stacks.
 *
 * Usage: node scripts/build-nutation-series.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const phpSource = readFileSync(path.join(root, 'api', 'astrology', 'ephemeris_tables.php'), 'utf8');

const tableMatch = /'nutation'\s*=>\s*\[([\s\S]*?)\n\s*\],/.exec(phpSource);
if (!tableMatch) {
  throw new Error('Could not locate the nutation table in api/astrology/ephemeris_tables.php');
}

const rows = [...tableMatch[1].matchAll(/\[([-\d,\s.]+)\]/g)].map(match =>
  match[1]
    .split(',')
    .map(value => Number(value.trim()))
);
if (rows.length !== 63) {
  throw new Error(`Expected 63 IAU 1980 nutation terms, found ${rows.length}`);
}
for (const row of rows) {
  if (row.length !== 9 || row.some(value => !Number.isFinite(value))) {
    throw new Error(`Malformed nutation row: ${JSON.stringify(row)}`);
  }
}

const lines = rows.map(row => `  [${row.map(v => String(v)).join(', ')}],`).join('\n');

const output = `/**
 * GENERATED FILE — do not edit by hand.
 *
 * IAU 1980 theory of nutation, full 63-term series for Δψ (nutation in
 * longitude) and Δε (nutation in obliquity), generated by
 * scripts/build-nutation-series.mjs from the PHP engine's own table
 * (api/astrology/ephemeris_tables.php) so both stacks apply an identical Δψ.
 *
 * Row layout — [D, M, M', F, Ω, Δψ coefficient, Δψ rate, Δε coefficient, Δε rate]
 * where the coefficients are in units of 0.0001 arcsecond and the rates are the
 * per-Julian-century corrections. Argument = the dot product of the first five
 * values with the fundamental arguments of the nutation theory.
 */
export const NUTATION_1980_SERIES: ReadonlyArray<readonly number[]> = [
${lines}
];
`;

writeFileSync(path.join(root, 'src', 'lib', 'astrology', 'nutationSeries.ts'), output, 'utf8');
console.log(`Wrote ${rows.length} IAU 1980 nutation terms to src/lib/astrology/nutationSeries.ts`);
