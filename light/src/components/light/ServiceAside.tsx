import React from 'react';
import { Check, Eye, FileText, Sparkles, Info } from 'lucide-react';
import { SAMPLE_REPORT_COPY, type AsidePanel } from '../../servicePanels';
import { useLightUi } from '../../lightContext';
import { LIVE_SITE } from '../../appConfig';

/**
 * The side column of a report page — the same three boxes the live pages carry
 * beside the order form ("What is included…", "See the report before you
 * order", the priest-team assurance), in the live wording and the live order.
 * Only the paint and the small preview notice are new.
 */
export const IncludedPanel: React.FC<{ panel: AsidePanel; accent?: 'brand' | 'accent' | 'rose' | 'leaf' }> = ({
  panel,
  accent = 'brand'
}) => (
  <section className="c-card space-y-4 p-6">
    <h2 className="flex items-center gap-2 text-[0.72rem] font-bold uppercase tracking-[0.14em] text-ink">
      <FileText className="h-4 w-4 text-brand" aria-hidden />
      <span>{panel.heading}</span>
    </h2>
    {panel.intro ? <p className="text-[0.8rem] leading-relaxed text-muted">{panel.intro}</p> : null}
    <ul className="space-y-2.5 text-[0.82rem] text-ink-soft">
      {panel.items.map((item) => (
        <li key={item.title} className="flex items-start gap-2">
          <Check
            className={`mt-0.5 h-3.5 w-3.5 shrink-0 ${
              accent === 'rose'
                ? 'text-rose'
                : accent === 'leaf'
                  ? 'text-leaf'
                  : accent === 'accent'
                    ? 'text-accent'
                    : 'text-brand'
            }`}
            aria-hidden
          />
          <span>
            <strong className="font-bold text-ink">{item.title}:</strong> {item.text}
          </span>
        </li>
      ))}
    </ul>
  </section>
);

export const SampleReportPanel: React.FC<{ sampleNote: string }> = ({ sampleNote }) => {
  const { notify } = useLightUi();

  return (
    <section className="c-card space-y-3 border-brand/40 p-5">
      <div className="flex items-center gap-2 text-[0.72rem] font-bold uppercase tracking-[0.14em] text-ink">
        <Eye className="h-4 w-4 text-brand" aria-hidden />
        <span>{SAMPLE_REPORT_COPY.heading}</span>
      </div>
      <p className="text-[0.78rem] leading-relaxed text-muted">{sampleNote}</p>
      <button
        type="button"
        onClick={() =>
          notify(`Sample reports are generated by the live site — opening ${LIVE_SITE.replace('https://', '')}.`)
        }
        className="c-btn c-btn-soft w-full justify-center"
      >
        <Eye className="h-4 w-4" aria-hidden />
        <span>{SAMPLE_REPORT_COPY.button}</span>
      </button>
      <p className="text-[0.72rem] leading-relaxed text-faint">{SAMPLE_REPORT_COPY.note}</p>
    </section>
  );
};

